"""Calendar export without OAuth — .ics for deadlines and follow-ups."""

from __future__ import annotations

from datetime import datetime, timedelta
from typing import Any


def _fmt(dt: datetime) -> str:
    return dt.strftime("%Y%m%dT%H%M%SZ")


def _escape(text: str) -> str:
    return (
        (text or "")
        .replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\n", "\\n")
    )


def build_ics(events: list[dict[str, Any]], calendar_name: str = "Academic Outreach") -> str:
    now = datetime.utcnow()
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//Academic Outreach Studio//EN",
        "CALSCALE:GREGORIAN",
        f"X-WR-CALNAME:{_escape(calendar_name)}",
    ]
    for i, ev in enumerate(events):
        start = ev.get("start") or now + timedelta(days=7)
        if isinstance(start, str):
            try:
                start = datetime.fromisoformat(start.replace("Z", ""))
            except ValueError:
                start = now + timedelta(days=7)
        end = ev.get("end") or (start + timedelta(hours=1))
        uid = ev.get("uid") or f"aos-{i}-{int(start.timestamp())}@academic-outreach.studio"
        lines.extend(
            [
                "BEGIN:VEVENT",
                f"UID:{uid}",
                f"DTSTAMP:{_fmt(now)}",
                f"DTSTART:{_fmt(start)}",
                f"DTEND:{_fmt(end)}",
                f"SUMMARY:{_escape(ev.get('summary') or 'Research task')}",
                f"DESCRIPTION:{_escape(ev.get('description') or '')}",
                "END:VEVENT",
            ]
        )
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


def events_from_tracker(conn) -> list[dict[str, Any]]:
    """Build calendar events from application deadlines and reminders."""
    events: list[dict[str, Any]] = []
    rows = conn.execute(
        """
        SELECT a.id, a.state, o.deadline, r.display_name
        FROM application a
        JOIN opportunity o ON o.id = a.opportunity_id
        JOIN researcher r ON r.id = o.researcher_id
        WHERE o.deadline IS NOT NULL AND o.deadline != ''
        ORDER BY o.deadline
        LIMIT 40
        """
    ).fetchall()
    for row in rows:
        try:
            day = datetime.fromisoformat(str(row["deadline"])[:10])
        except ValueError:
            continue
        events.append(
            {
                "uid": f"deadline-{row['id']}@academic-outreach.studio",
                "start": day.replace(hour=9),
                "end": day.replace(hour=10),
                "summary": f"Research application deadline — {row['display_name']}",
                "description": f"Application state: {row['state']}. Submit documents before the deadline.",
            }
        )
    reminders = conn.execute(
        """
        SELECT id, due_on, kind FROM reminder
        WHERE dismissed = 0 AND due_on IS NOT NULL AND due_on != ''
        ORDER BY due_on
        LIMIT 40
        """
    ).fetchall()
    for rem in reminders:
        try:
            due = datetime.fromisoformat(str(rem["due_on"])[:10])
        except ValueError:
            continue
        kind = rem["kind"] or "reminder"
        summary = (
            "Follow-up with professor"
            if "follow" in kind.lower()
            else f"Research reminder — {kind}"
        )
        events.append(
            {
                "uid": f"reminder-{rem['id']}@academic-outreach.studio",
                "start": due.replace(hour=10),
                "end": due.replace(hour=11),
                "summary": summary,
                "description": "Review before sending. Generated by Academic Outreach Studio.",
            }
        )
    return events
